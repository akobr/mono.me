// Writes generated/catalog/project-settings.ts from the catalog of project settings of the conformance suite
// (src/Platform/Storyteller/conformance/project-settings.json): the allowed values as `as const` arrays and their literal
// types, so the SDK carries the catalog of the API without a second, hand-kept copy. Formatted by Prettier, as Orval
// formats its output, so the check that generated/ matches a fresh `npm run generate` guards this file too.
// Usage: npm run generate                       (Orval, then this script)
//        node scripts/generate-catalog.mjs      (this file only)
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { format, resolveConfig } from 'prettier'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const source = resolve(root, '../../conformance/project-settings.json')
const target = join(root, 'generated', 'catalog', 'project-settings.ts')

const literal = (value) => JSON.stringify(value)

const list = (values, name) => {
  if (!Array.isArray(values) || values.length === 0 || values.some((value) => typeof value !== 'string' || value.length === 0)) {
    throw new Error(`The catalog's ${name} is not a list of strings.`)
  }

  return `[${values.map(literal).join(', ')}] as const`
}

export function renderCatalog(file) {
  const catalog = file?.catalog

  if (typeof catalog !== 'object' || catalog === null) {
    throw new Error('The project settings file has no catalog.')
  }

  const builtIn = Object.fromEntries(catalog.typeCodes.map((code) => {
    const { label, plural, color, icon } = catalog.builtIn?.[code] ?? {}
    return [code, { label, plural, color, icon }]
  }))

  return `/**
 * Generated by scripts/generate-catalog.mjs from src/Platform/Storyteller/conformance/project-settings.json.
 * Do not edit manually: change the catalog of the conformance suite and run npm run generate.
 */

/** The Format member of a project settings file, such as the project-settings.json of a data set. */
export const projectSettingsFormat = ${literal(catalog.format)} as const;

/** The annotation type codes, in the order clients show them and the API writes them. */
export const projectSettingsTypeCodes = ${list(catalog.typeCodes, 'typeCodes')};

/** The colors of an annotation type, as the API stores them. */
export const typeColors = ${list(catalog.colors, 'colors')};

export type TypeColor = (typeof typeColors)[number];

/** The icons of an annotation type (Iconify names of the Lucide set), as the API stores them. */
export const typeIconNames = ${list(catalog.icons, 'icons')};

export type TypeIconName = (typeof typeIconNames)[number];

/** How clients show dates. */
export const dateFormats = ${list(catalog.dateFormats, 'dateFormats')};

export type DateFormat = (typeof dateFormats)[number];

/** The appearance of every annotation type of a project that sets none. */
export const builtInTypeAppearances = ${literal(builtIn)} as const;

/** What an absent DefaultTimeZone and DateFormat mean. */
export const projectSettingsDefaults = ${literal(catalog.defaults)} as const;

/** The longest label and plural, in UTF-16 code units after trimming. */
export const projectSettingsLimits = ${literal(catalog.limits)} as const;

/** The IANA time zone ids of the tz database (links, Etc zones and UTC included) a project may start annotations in. */
export const catalogTimeZones = ${list(catalog.timeZones, 'timeZones')};

export type CatalogTimeZone = (typeof catalogTimeZones)[number];
`
}

export async function writeCatalog() {
  const file = JSON.parse(readFileSync(source, 'utf8'))
  const options = (await resolveConfig(target)) ?? {}
  const text = await format(renderCatalog(file), { ...options, parser: 'typescript' })

  mkdirSync(dirname(target), { recursive: true })
  writeFileSync(target, text)
  console.log(`Catalog written to ${target}`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  await writeCatalog()
}
